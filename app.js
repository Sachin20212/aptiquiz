function shuffle(array){
  const copy = [...array];
  for(let i=copy.length-1;i>0;i--){
    const j=Math.floor(Math.random()*(i+1));
    [copy[i],copy[j]]=[copy[j],copy[i]];
  }
  return copy;
}

function buildGameQuestions(){
  // Never repeat a question until every question in the worldwide bank has been used.
  if(state.usedQuestionIds.size + QUESTIONS_PER_GAME > questionBank.length){
    state.usedQuestionIds.clear();
  }
  const available = questionBank
    .map((q,index)=>({q,index}))
    .filter(item=>!state.usedQuestionIds.has(item.index));
  const selected = shuffle(available).slice(0, QUESTIONS_PER_GAME);
  selected.forEach(item=>state.usedQuestionIds.add(item.index));
  state.gameQuestions = selected.map(item=>item.q);
}

